import { choosePhoto } from './casting-helpers';
import { expect, test } from '@playwright/test';

test('file a scripted run by show and reuse the first episode cast', async ({ page }, testInfo) => {
  test.setTimeout(90_000);
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.goto('/');
  await expect(page.locator('#status')).toContainText('WASM READY');
  const prop = page.locator('[data-prop="script"]');
  await prop.click();
  const can = page.getByRole('dialog');
  await can.getByRole('button', { name: 'Ideas', exact: true }).click();
  await expect(can.locator('.can-side-sticker')).toHaveText('Ideas');
  await page.screenshot({ path: testInfo.outputPath('film-can-branch.png') });
  await can.getByRole('button', { name: 'Back', exact: true }).click();
  await expect(can.getByRole('button', { name: 'Ideas', exact: true })).toBeFocused();
  await page.keyboard.press('Escape');
  await expect(prop).toBeFocused();
  await prop.click();
  for (const choice of ['Ideas', 'Draft new', 'Fiction', 'Series']) {
    await can.getByRole('button', { name: choice, exact: true }).click();
  }
  await page.getByLabel('Film title').fill('Harbour Lights');
  await page.getByLabel('Episode 1 tension', { exact: true }).fill('0.1');
  await page.getByLabel('Episode 2 tension', { exact: true }).fill('0.9');
  await page.getByRole('button', { name: 'Open scripted series binder' }).click();
  const box = page.locator('.script-file-box');
  await expect(box.locator('.script-file-tab')).toHaveCount(1);
  await box.getByRole('button', { name: /Harbour Lights/ }).click();
  await expect(box.locator('.script-file-tab')).toHaveCount(3);
  await expect(box.getByRole('button', { name: /Episode 1/ })).toContainText(/Commission a script|Open the writing file/);
  await page.screenshot({ path: testInfo.outputPath('show-file-box.png'), animations: 'disabled' });
  const episode = (n: number) => box.getByRole('button', { name: new RegExp(`Episode ${n}`) });
  await episode(2).click();
  const film = page.locator('.film-project');
  await expect(film).toContainText('Tension target 90%');
  await expect(film).toContainText('Large shifts');
  await film.getByRole('button', { name: 'Close file' }).click();
  await expect(episode(2)).toBeFocused();

  await episode(1).click();
  await choosePhoto(page, film.locator('#film-writer-photo'), 'Ada Mercer');
  await film.getByRole('button', { name: 'Commission script' }).click();
  await film.getByRole('button', { name: 'Advance to script delivery' }).click();
  await film.getByRole('button', { name: 'Accept script' }).click();
  await choosePhoto(page, film.locator('#film-actor-photo-0'), 'Nina Bell');
  await choosePhoto(page, film.locator('#film-actor-photo-1'), 'Sam Ives');
  await choosePhoto(page, film.locator('#film-director-photo'), 'Inez Park');
  await film.getByRole('button', { name: 'Next page' }).click();
  await film.getByRole('button', { name: 'Confirm film booking' }).click();
  await film.getByRole('button', { name: 'Advance to film delivery' }).click();
  await expect(film.getByRole('button', { name: 'Open in programme library' })).toBeVisible();

  await film.getByRole('button', { name: 'Close file' }).click();
  await episode(2).click();
  await choosePhoto(page, film.locator('#film-writer-photo'), 'Ada Mercer');
  await film.getByRole('button', { name: 'Commission script' }).click();
  await film.getByRole('button', { name: 'Advance to script delivery' }).click();
  await film.getByRole('button', { name: 'Accept script' }).click();
  await expect(film).toContainText('The recurring actors keep their established roles.');
  await expect(film.locator('#film-actor-photo-0')).toBeDisabled();
  await expect(film.locator('#film-actor-photo-0')).toContainText('Nina Bell');
  await expect(film.locator('#film-actor-photo-1')).toBeDisabled();
  await expect(film.locator('#film-actor-photo-1')).toContainText('Sam Ives');
});

test.describe('film can on a narrow touch display', () => {
  test.use({ hasTouch: true, reducedMotion: 'reduce', viewport: { width: 390, height: 844 } });
  test('open scripts and use page controls without losing the draft', async ({ page }, testInfo) => {
    await page.goto('/');
    await expect(page.locator('#status')).toContainText('WASM READY');
    const prop = page.locator('[data-prop="script"]');
    await prop.tap();
    const can = page.getByRole('dialog');
    await can.getByRole('button', { name: 'Scripts', exact: true }).tap();
    await expect(can.locator('.can-side-sticker')).toHaveText('Scripts');
    await expect(can.getByRole('button', { name: 'Draft new' })).toHaveCount(0);
    const bounds = await can.boundingBox();
    expect(bounds!.x).toBeGreaterThanOrEqual(0);
    expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(390);
    await page.touchscreen.tap(5, 5);
    await expect(can).toBeHidden();
    await prop.tap();
    await can.getByRole('button', { name: 'Ideas', exact: true }).tap();
    await can.getByRole('button', { name: 'Existing', exact: true }).tap();
    await page.getByRole('button', { name: 'Draft film', exact: true }).tap();
    await page.getByLabel('Film title').fill('An Afternoon at the Pier');
    await page.getByLabel('Description').fill('A quiet seaside story.');
    await page.getByText('Take your time', { exact: true }).tap();
    await page.getByRole('button', { name: 'Develop this idea' }).tap();
    const film = page.locator('.film-project');
    await film.getByRole('button', { name: 'Next page' }).tap();
    await expect(film.getByText('2 / 2 · Idea')).toBeVisible();
    await page.keyboard.press('Escape');
    await expect(prop).toBeFocused();
    await prop.tap();
    await can.getByRole('button', { name: 'Return to desk papers' }).tap();
    await expect(film.getByText('2 / 2 · Idea')).toBeVisible();
    await expect(film).toContainText('An Afternoon at the Pier');
    await page.screenshot({ path: testInfo.outputPath('production-narrow.png') });
  });
});
