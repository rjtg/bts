import { pickTime, setAdLoad } from './planner-helpers';
import { expect, test } from '@playwright/test';

test('find a title for a 45-minute gap and keep the shelf and timeline place across desks', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.goto('/#planning');
  await expect(page.locator('#status')).toContainText('WASM READY');
  await expect(page.locator('.series-box > summary')).toHaveText('Neighbourhood Laughs · 3 episodes');
  await expect(page.locator('[data-programme="1"]')).toBeHidden();
  await pickTime(page, 75);
  await page.locator('#place').click();
  await page.locator('#jump-evening').click();
  await page.getByRole('button', { name: 'Choose placement Day 1 · 18:00' }).click();
  await setAdLoad(page, 33);
  await expect(page.locator('#desk-notes')).toContainText('18:00 · 45 min');
  await page.getByRole('checkbox', { name: 'Fill Next Gap' }).check();
  await expect(page.locator('[data-programme="2"]')).toHaveCount(0);
  await page.getByRole('searchbox', { name: 'Find a title' }).fill('laughs');
  await page.locator('[data-programme="1"]').press('Enter');
  await expect(page.locator('#slot-picker')).toHaveCount(0);
  await expect(page.locator('.shelf-slot-preview')).toContainText('Neighbourhood Laughs');
  await expect(page.locator('#paper-on-desk .desk-paper-tabs')).toBeVisible();
  await expect(page.locator('#desk-tape')).toContainText('Episode 1 · 30 min');
  await expect(page.locator('[data-programme="1"]')).toHaveClass(/fits-selected-gap/);
  if (process.env.BTS_DESK_SCREENSHOTS) await page.screenshot({ path: '/tmp/bts-live-console.png', fullPage: true });
  await page.getByRole('button', { name: 'Place at 18:00' }).press('Enter');
  const scroller = page.locator('#timeline-scroller');
  const scroll = await scroller.evaluate(el => el.scrollLeft);
  await page.locator('#open-ad-sales').click();
  await expect(page.locator('[data-desk="planning"]')).toBeVisible();
  await page.getByRole('spinbutton', { name: 'Minutes to list' }).fill('10');
  await page.getByRole('button', { name: 'Set ad block' }).click();
  await expect(page.locator('#ad-minute-market')).toContainText('40 min runtime · until 18:40');
  await page.getByRole('button', { name: 'Close file' }).click();
  await expect(page.getByRole('region', { name: 'Airing dossier' })).toBeHidden();
  await expect(page.getByRole('searchbox')).toHaveValue('laughs');
  await expect(page.getByRole('checkbox', { name: 'Fill Next Gap' })).toBeChecked();
  await page.locator('[data-station="1"] [data-start-minute="1080"]').press('Enter');
  await expect(page.locator('#selected-name')).toHaveText('Neighbourhood Laughs');
  await expect(page.locator('#selected-runtime')).toHaveText('40 min airtime');
  expect(await scroller.evaluate(el => el.scrollLeft)).toBe(scroll);
  await page.getByRole('checkbox', { name: 'Fill Next Gap' }).uncheck();
  await page.locator('[data-programme="1"]').click();
  const record = page.locator('#paper-on-desk');
  await expect(record).toContainText('no cast list on file');
  await record.getByRole('button', { name: 'Audience estimate' }).click();
  await expect(record).toContainText('Slot under consideration');
  if (process.env.BTS_DESK_SCREENSHOTS) await page.screenshot({ path: '/tmp/bts-live-station-file.png' });
  await record.getByRole('button', { name: 'Airing ledger' }).click();
  await expect(record).toContainText('Times aired0');
  await page.locator('[data-station="1"] [data-start-minute="1080"]').click();
  await page.locator('#advance-selected').click();
  await page.locator('[data-programme="1"]').click();
  await record.getByRole('button', { name: 'Airing ledger' }).click();
  await expect(record).toContainText('Times aired1');
  await expect(record).toContainText('Airing costs to date150 Funds');
  await record.getByRole('button', { name: 'Saturday · Day 1 · 18:00' }).click();
  await expect(page.locator('#selected-result')).toBeVisible();
  await expect(page.locator('#results')).toBeVisible();
});

test('pause locks the active desk and preserves its unsubmitted minutes on resume', async ({ page }) => {
  await page.setViewportSize({ width: 420, height: 850 });
  await page.goto('/#planning');
  await expect(page.locator('#playback-state')).toHaveText('STANDBY');
  await page.clock.install();
  await page.getByRole('button', { name: 'Open tape shelf' }).click();
  await page.locator('#place').click();
  await page.locator('#day-agenda').getByRole('button', { name: /18:00 · Your channel/ }).click();
  await page.locator('#open-ad-sales').click();
  const minutes = page.getByRole('spinbutton', { name: 'Minutes to list' });
  await minutes.fill('10');
  await page.getByRole('button', { name: 'Play', exact: true }).click();
  await page.getByRole('button', { name: 'Pause', exact: true }).click();
  const pause = page.getByRole('dialog', { name: 'OFF AIR' });
  await expect(pause).toBeVisible();
  await expect(page.getByRole('button', { name: 'Continue' })).toBeFocused();
  await expect(page.locator('#controls')).toHaveAttribute('inert', '');
  await page.locator('.rail a[href="#planning"]').evaluate((link: HTMLElement) => link.focus());
  await expect(page.getByRole('button', { name: 'Continue' })).toBeFocused();
  await page.keyboard.press('Escape');
  await page.clock.runFor(5000);
  await expect(pause).toBeVisible();
  await expect(page.locator('#clock')).toContainText('00:00');
  if (process.env.BTS_DESK_SCREENSHOTS) await page.screenshot({ path: '../contrib/focused-desks/pause.png' });
  await page.getByRole('button', { name: 'Continue' }).click();
  await expect(pause).toBeHidden();
  await expect(page.locator('#play-pause')).toBeFocused();
  await expect(minutes).toHaveValue('10');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
